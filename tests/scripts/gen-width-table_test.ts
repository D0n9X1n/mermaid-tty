import test, { type TestContext } from 'node:test'
import assert from 'node:assert/strict'
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { spawnSync } from 'node:child_process'

// Runs the generator on `text`, saved as EastAsianWidth.txt in a fresh temp dir.
function generate(t: TestContext, text: string | Uint8Array) {
  const dir = mkdtempSync(join(tmpdir(), 'mermaid-tty-eaw-'))
  t.after(() => rmSync(dir, { recursive: true, force: true }))
  const file = join(dir, 'EastAsianWidth.txt')
  writeFileSync(file, text)
  return spawnSync(process.execPath, ['scripts/gen-width-table.ts', file])
}

// A synthetic file whose data lines are copied from Unicode 16.0.0: W, F, N, Na, A
// and H lines; single code points and ranges; comments and blank lines; adjacent
// W and F ranges that merge (3000..3004 across a comment, FF01..FF07, 20000..2A6FF);
// and 26F2..26F3 and 26F5, one code point apart, which stay separate.
const EAW = `# EastAsianWidth-99.1.2.txt
# Date: 2099-01-01, 00:00:00 GMT
# A synthetic test file; its data lines are copied from Unicode 16.0.0.
#
# @missing: 0000..10FFFF; N

0000..001F     ; N  # Cc    [32] <control-0000>..<control-001F>
0020           ; Na # Zs         SPACE
00A1           ; A  # Po         INVERTED EXCLAMATION MARK
1100..115F     ; W  # Lo    [96] HANGUL CHOSEONG KIYEOK..HANGUL CHOSEONG FILLER
1160..11FF     ; N  # Lo   [160] HANGUL JUNGSEONG FILLER..HANGUL JONGSEONG SSANGNIEUN
20A9           ; H  # Sc         WON SIGN
231A..231B     ; W  # So     [2] WATCH..HOURGLASS
23F0           ; W  # So         ALARM CLOCK
23F1..23F2     ; N  # So     [2] STOPWATCH..TIMER CLOCK
23F3           ; W  # So         HOURGLASS WITH FLOWING SAND
26F2..26F3     ; W  # So     [2] FOUNTAIN..FLAG IN HOLE
26F4           ; A  # So         FERRY
26F5           ; W  # So         SAILBOAT

3000           ; F  # Zs         IDEOGRAPHIC SPACE
3001..3003     ; W  # Po     [3] IDEOGRAPHIC COMMA..DITTO MARK
# A comment between two ranges that merge.
3004           ; W  # So         JAPANESE INDUSTRIAL STANDARD SYMBOL
FF01..FF03     ; F  # Po     [3] FULLWIDTH EXCLAMATION MARK..FULLWIDTH NUMBER SIGN
FF04           ; F  # Sc         FULLWIDTH DOLLAR SIGN
FF05..FF07     ; F  # Po     [3] FULLWIDTH PERCENT SIGN..FULLWIDTH APOSTROPHE
FF61           ; H  # Po         HALFWIDTH IDEOGRAPHIC FULL STOP
FF62           ; H  # Ps         HALFWIDTH LEFT CORNER BRACKET
1F300..1F320   ; W  # So    [33] CYCLONE..SHOOTING STAR
1F321..1F32C   ; N  # So    [12] THERMOMETER..WIND BLOWING FACE
20000..2A6DF   ; W  # Lo [42720] CJK UNIFIED IDEOGRAPH-20000..CJK UNIFIED IDEOGRAPH-2A6DF
2A6E0..2A6FF   ; W  # Cn    [32] <reserved-2A6E0>..<reserved-2A6FF>
E0100..E01EF   ; A  # Mn   [240] VARIATION SELECTOR-17..VARIATION SELECTOR-256
100000..10FFFD ; A  # Co [65534] <private-use-100000>..<private-use-10FFFD>

# EOF
`

const WANT = `// Generated by scripts/gen-width-table.ts from Unicode 99.1.2 EastAsianWidth.txt; do not edit.
// The East Asian Width W and F ranges, merged: inclusive [lo, hi] pairs in ascending order.
export const WIDE: readonly number[] = [
  0x1100, 0x115F,
  0x231A, 0x231B,
  0x23F0, 0x23F0,
  0x23F3, 0x23F3,
  0x26F2, 0x26F3,
  0x26F5, 0x26F5,
  0x3000, 0x3004,
  0xFF01, 0xFF07,
  0x1F300, 0x1F320,
  0x20000, 0x2A6FF,
]
`

test('A4.width-table: the generator keeps W and F, merges adjacent ranges and names the version', t => {
  const r = generate(t, EAW)
  assert.equal(r.status, 0, r.stderr.toString())
  assert.equal(r.stdout.toString(), WANT)
})

test('A4.width-table: the generator throws on a malformed line', t => {
  for (const line of ['1100..115F     ; X  # an unknown class', '1100..115F       W', '11G0           ; W']) {
    const r = generate(t, `# EastAsianWidth-99.1.2.txt\n\n${line}\n`)
    assert.notEqual(r.status, 0, line)
    assert.ok(r.stderr.toString().includes('unexpected line: ' + line), r.stderr.toString())
  }
})

const EAW_URL = 'https://www.unicode.org/Public/16.0.0/ucd/EastAsianWidth.txt'

// Downloads url, or says why the network could not deliver it.
async function download(url: string): Promise<{ status: number, body: Buffer } | { error: string }> {
  try {
    const res = await fetch(url, { signal: AbortSignal.timeout(60_000) })
    return { status: res.status, body: Buffer.from(await res.arrayBuffer()) }
  } catch (e) {
    const cause = e instanceof Error && e.cause instanceof Error ? ': ' + e.cause.message : ''
    return { error: (e instanceof Error ? e.message : String(e)) + cause }
  }
}

test('A4.width-table: regenerating from Unicode 16.0.0 EastAsianWidth.txt reproduces core/width-table.ts byte for byte', async t => {
  const got = await download(EAW_URL)
  if ('error' in got) { t.skip(`network unavailable; cannot download ${EAW_URL} (${got.error})`); return }
  assert.equal(got.status, 200, `${EAW_URL}: HTTP ${got.status}`)
  const r = generate(t, got.body)
  assert.equal(r.status, 0, r.stderr.toString())
  // latin1 maps each byte to one character, so equal strings mean equal bytes.
  assert.equal(r.stdout.toString('latin1'), readFileSync('core/width-table.ts', 'latin1'))
})

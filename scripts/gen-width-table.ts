// Generates core/width-table.ts from a Unicode EastAsianWidth.txt:
//   node scripts/gen-width-table.ts <EastAsianWidth.txt> > core/width-table.ts
// Keeps the W and F ranges, merges adjacent ones, and names the Unicode
// version read from the file's first line.
import { readFileSync } from 'node:fs'

const file = process.argv[2]
if (!file) {
  throw new Error('usage: node scripts/gen-width-table.ts <EastAsianWidth.txt>')
}
const text = readFileSync(file, 'utf8')
const version = /^# EastAsianWidth-(\d+\.\d+\.\d+)\.txt/.exec(text)?.[1]
if (!version) {
  throw new Error(file + ': the first line does not name an EastAsianWidth version')
}

const ranges: [number, number][] = []
for (const line of text.split(/\r?\n/)) {
  const data = line.replace(/#.*/, '').trim()
  if (!data) {
    continue
  }
  const m = /^([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?\s*;\s*(A|F|H|N|Na|W)$/.exec(data)
  if (!m) {
    throw new Error(file + ': unexpected line: ' + line)
  }
  if (m[3] !== 'W' && m[3] !== 'F') {
    continue
  }
  const lo = parseInt(m[1]!, 16)
  ranges.push([lo, m[2] ? parseInt(m[2], 16) : lo])
}

ranges.sort((a, b) => a[0] - b[0])
const merged: [number, number][] = []
for (const [lo, hi] of ranges) {
  const last = merged[merged.length - 1]
  if (last && lo <= last[1] + 1) {
    last[1] = Math.max(last[1], hi)
  } else {
    merged.push([lo, hi])
  }
}

const hex = (n: number) => '0x' + n.toString(16).toUpperCase()
process.stdout.write(
  [
    `// Generated by scripts/gen-width-table.ts from Unicode ${version} EastAsianWidth.txt; do not edit.`,
    '// The East Asian Width W and F ranges, merged: inclusive [lo, hi] pairs in ascending order.',
    'export const WIDE: readonly number[] = [',
    ...merged.map(([lo, hi]) => `  ${hex(lo)}, ${hex(hi)},`),
    ']',
    '',
  ].join('\n'),
)

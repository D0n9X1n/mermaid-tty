// Generates core/box-table.ts: the Box Drawing glyph for each set of arm weights, keyed 'urdl' (up right down left; 0
// none, 1 light, 2 heavy). Usage: node scripts/gen-box-table.ts <UnicodeData.txt> > core/box-table.ts Source:
// https://www.unicode.org/Public/16.0.0/ucd/UnicodeData.txt
import { readFileSync } from 'node:fs'

const SKIP = /\b(DOUBLE|SINGLE|ARC|DASH|DIAGONAL)\b/
const DIRS: Readonly<Record<string, readonly number[]>> = {
  UP: [0],
  RIGHT: [1],
  DOWN: [2],
  LEFT: [3],
  VERTICAL: [0, 2],
  HORIZONTAL: [1, 3],
}
const WEIGHTS: Readonly<Record<string, number>> = { LIGHT: 1, HEAVY: 2 }

type Part = { dirs: number[]; weight: number | undefined }

// One side of ' AND ': directions plus at most one weight, in either order.
function parsePart(text: string, name: string): Part {
  const part: Part = { dirs: [], weight: undefined }
  for (const word of text.split(' ')) {
    const dirs = DIRS[word]
    const weight = WEIGHTS[word]
    if (dirs) {
      part.dirs.push(...dirs)
    } else if (weight !== undefined && part.weight === undefined) {
      part.weight = weight
    } else {
      throw new Error(`unexpected '${word}' in ${name}`)
    }
  }

  if (part.dirs.length === 0) {
    throw new Error(`no direction in ${name}`)
  }

  return part
}

// 'LIGHT DOWN AND RIGHT' -> '0110'; 'UP HEAVY AND RIGHT DOWN LIGHT' -> '2110'. A part without a weight takes the other
// part's.
function armsOf(name: string): string {
  const parts = name.split(' AND ').map((text) => parsePart(text, name))
  if (parts.length > 2) {
    throw new Error(`more than one AND in ${name}`)
  }

  const arms = [0, 0, 0, 0]
  for (const [i, part] of parts.entries()) {
    const weight = part.weight ?? parts[1 - i]?.weight
    if (weight === undefined) {
      throw new Error(`no weight in ${name}`)
    }

    for (const d of part.dirs) {
      if (arms[d]) {
        throw new Error(`arm named twice in ${name}`)
      }

      arms[d] = weight
    }
  }

  return arms.join('')
}

const file = process.argv[2]
if (!file) {
  throw new Error('usage: node scripts/gen-box-table.ts <UnicodeData.txt> > core/box-table.ts')
}

const rows: string[] = []
const seen = new Set<string>()
for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
  const [hex, name] = line.split(';')
  if (hex === undefined || name === undefined) {
    continue
  }

  const cp = parseInt(hex, 16)
  if (!(cp >= 0x2500 && cp <= 0x257f) || SKIP.test(name)) {
    continue
  }

  const arms = armsOf(name.replace(/^BOX DRAWINGS /, ''))
  if (seen.has(arms)) {
    throw new Error(`arms ${arms} named twice, again by ${name}`)
  }

  seen.add(arms)
  rows.push(`  '${arms}': '${String.fromCodePoint(cp)}', // U+${hex} ${name}`)
}

process.stdout.write(
  [
    '// Generated by scripts/gen-box-table.ts from UnicodeData.txt; do not edit.',
    '// The Box Drawing glyph for each set of arms, keyed up right down left (0 none, 1 light, 2 heavy).',
    'export const BOX: Readonly<Record<string, string>> = {',
    ...rows,
    '}',
    '',
  ].join('\n'),
)
